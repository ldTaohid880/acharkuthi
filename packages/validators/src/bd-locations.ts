export function districtsOf(division: string): string[] {
  return Object.keys(RAW[division] ?? {});
}

export function upazilasOf(division: string, district: string): string[] {
  const list = RAW[division]?.[district];
  return list ? list.split("|") : [];
}

/** True when the three names form a real path in the list. The server checks this before taking an order. */
export function isKnownLocation(division: string, district: string, upazila: string): boolean {
  return upazilasOf(division, district).includes(upazila);
}

/** The district whose addresses get the "inside Dhaka" delivery charge. */
export const DHAKA_DISTRICT = "ঢাকা";

/** The division a district belongs to (orders only store the district). */
export function divisionOf(district: string): string | undefined {
  return DIVISIONS.find((d) => district in (RAW[d] ?? {}));
}

